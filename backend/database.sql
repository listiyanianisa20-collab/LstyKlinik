-- Skema Sistem Informasi Akuntansi Penjualan Lsty Klinik

create table if not exists pelanggan (
  id_pelanggan bigint generated by default as identity primary key,
  nama text not null check (length(trim(nama)) > 0),
  no_hp text not null check (length(trim(no_hp)) > 0),
  alamat text not null default '',
  tanggal_daftar date not null default current_date
);

-- Pulihkan tabel lama yang sudah ada tanpa kolom kunci sesuai ERD.
do $$
begin
  if not exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'pelanggan' and column_name = 'id_pelanggan'
  ) then
    if exists (
      select 1 from information_schema.columns
      where table_schema = 'public' and table_name = 'pelanggan' and column_name = 'id'
    ) then
      alter table public.pelanggan rename column id to id_pelanggan;
    else
      alter table public.pelanggan
        add column id_pelanggan bigint generated by default as identity;
    end if;
  end if;

  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.pelanggan'::regclass and contype = 'p'
  ) then
    alter table public.pelanggan
      add constraint pelanggan_pkey primary key (id_pelanggan);
  elsif not exists (
    select 1 from pg_constraint
    where conrelid = 'public.pelanggan'::regclass
      and contype in ('p', 'u')
      and conkey = array[(
        select attnum from pg_attribute
        where attrelid = 'public.pelanggan'::regclass and attname = 'id_pelanggan'
      )]::smallint[]
  ) then
    alter table public.pelanggan
      add constraint pelanggan_id_pelanggan_key unique (id_pelanggan);
  end if;
end;
$$;

alter table public.pelanggan add column if not exists nama text;
alter table public.pelanggan add column if not exists no_hp text;
alter table public.pelanggan add column if not exists alamat text;
alter table public.pelanggan add column if not exists tanggal_daftar date;

update public.pelanggan
set nama = coalesce(nullif(trim(nama), ''), 'Pelanggan ' || id_pelanggan::text),
    no_hp = coalesce(nullif(trim(no_hp), ''), 'Belum diisi'),
    alamat = coalesce(alamat, ''),
    tanggal_daftar = coalesce(tanggal_daftar, current_date);

alter table public.pelanggan alter column nama set not null;
alter table public.pelanggan alter column no_hp set default 'Belum diisi';
alter table public.pelanggan alter column no_hp set not null;
alter table public.pelanggan alter column alamat set default '';
alter table public.pelanggan alter column alamat set not null;
alter table public.pelanggan alter column tanggal_daftar set default current_date;
alter table public.pelanggan alter column tanggal_daftar set not null;

-- Pertahankan nomor telepon lama, tetapi jangan wajibkan kolom non-ERD saat insert baru.
do $$
declare
  kolom_lama record;
begin
  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'pelanggan' and column_name = 'telepon'
  ) then
    execute $sql$
      update public.pelanggan
      set no_hp = nullif(trim(telepon::text), '')
      where no_hp = 'Belum diisi' and nullif(trim(telepon::text), '') is not null
    $sql$;
  end if;

  for kolom_lama in
    select column_name
    from information_schema.columns
    where table_schema = 'public'
      and table_name = 'pelanggan'
      and is_nullable = 'NO'
      and is_identity = 'NO'
      and column_default is null
      and column_name not in ('id_pelanggan', 'nama', 'no_hp', 'alamat', 'tanggal_daftar')
  loop
    execute format('alter table public.pelanggan alter column %I drop not null', kolom_lama.column_name);
  end loop;
end;
$$;

create table if not exists item (
  id_item bigint generated by default as identity primary key,
  nama_item text not null check (length(trim(nama_item)) > 0),
  jenis text not null check (jenis in ('Produk', 'Jasa Treatment')),
  harga_jual numeric(14, 2) not null check (harga_jual >= 0),
  harga_pokok numeric(14, 2) not null default 0 check (harga_pokok >= 0),
  stok integer,
  constraint item_stok_jenis_check check (
    (jenis = 'Produk' and stok is not null and stok >= 0)
    or (jenis = 'Jasa Treatment' and stok is null and harga_pokok = 0)
  )
);

create table if not exists penjualan (
  id_penjualan bigint generated by default as identity primary key,
  id_pelanggan bigint not null references pelanggan(id_pelanggan),
  tanggal date not null default current_date,
  metode_pembayaran text not null check (metode_pembayaran in ('Tunai', 'Transfer', 'Kredit')),
  status_pembayaran text not null default 'Lunas' check (status_pembayaran in ('Lunas', 'Belum Lunas')),
  total numeric(14, 2) not null default 0 check (total >= 0)
);

create table if not exists detail_penjualan (
  id_detail bigint generated by default as identity primary key,
  id_penjualan bigint not null references penjualan(id_penjualan) on delete cascade,
  id_item bigint not null references item(id_item),
  jumlah integer not null check (jumlah > 0),
  harga_satuan numeric(14, 2) not null check (harga_satuan >= 0),
  subtotal numeric(14, 2) not null check (subtotal >= 0)
);

create table if not exists cicilan (
  id_cicilan bigint generated by default as identity primary key,
  id_penjualan bigint not null references penjualan(id_penjualan) on delete cascade,
  cicilan_ke integer not null check (cicilan_ke > 0),
  jatuh_tempo date not null,
  nominal numeric(14, 2) not null check (nominal > 0),
  tanggal_bayar date,
  metode_bayar text check (metode_bayar in ('Tunai', 'Transfer')),
  catatan text not null default '',
  status text not null default 'Belum' check (status in ('Lunas', 'Belum')),
  constraint cicilan_penjualan_ke_key unique (id_penjualan, cicilan_ke),
  constraint cicilan_status_pembayaran_check check (
    (status = 'Belum' and tanggal_bayar is null and metode_bayar is null)
    or (status = 'Lunas' and tanggal_bayar is not null and metode_bayar is not null)
  )
);

alter table public.cicilan add column if not exists catatan text not null default '';

create index if not exists penjualan_tanggal_idx on penjualan(tanggal);
create index if not exists penjualan_pelanggan_idx on penjualan(id_pelanggan);
create index if not exists detail_penjualan_penjualan_idx on detail_penjualan(id_penjualan);
create index if not exists detail_penjualan_item_idx on detail_penjualan(id_item);
create index if not exists cicilan_penjualan_idx on cicilan(id_penjualan);
create index if not exists cicilan_jatuh_tempo_idx on cicilan(jatuh_tempo) where status = 'Belum';

-- Satu baris laporan mewakili satu item pada detail transaksi.
create or replace view view_laporan_penjualan with (security_invoker = true) as
select
  p.tanggal,
  p.id_penjualan,
  pl.nama as nama_pelanggan,
  i.id_item,
  i.nama_item,
  i.jenis,
  d.jumlah,
  d.harga_satuan,
  d.subtotal,
  p.metode_pembayaran,
  p.status_pembayaran
from penjualan p
join pelanggan pl on pl.id_pelanggan = p.id_pelanggan
join detail_penjualan d on d.id_penjualan = p.id_penjualan
join item i on i.id_item = d.id_item;

-- Jurnal berpasangan: kas/piutang, pendapatan, serta HPP dan persediaan produk.
create or replace view view_jurnal_umum with (security_invoker = true) as
with debit_penjualan as (
  select
    p.tanggal,
    p.id_penjualan,
    case p.metode_pembayaran
      when 'Kredit' then 'Piutang Usaha'
      when 'Transfer' then 'Bank'
      else 'Kas'
    end as akun,
    p.total as nilai
  from penjualan p
), pendapatan as (
  select
    p.tanggal,
    p.id_penjualan,
    case i.jenis
      when 'Produk' then 'Pendapatan Penjualan Produk'
      else 'Pendapatan Jasa Treatment'
    end as akun,
    sum(d.subtotal) as nilai
  from penjualan p
  join detail_penjualan d on d.id_penjualan = p.id_penjualan
  join item i on i.id_item = d.id_item
  group by p.tanggal, p.id_penjualan, i.jenis
), hpp_produk as (
  select
    p.tanggal,
    p.id_penjualan,
    sum(d.jumlah * i.harga_pokok) as nilai
  from penjualan p
  join detail_penjualan d on d.id_penjualan = p.id_penjualan
  join item i on i.id_item = d.id_item
  where i.jenis = 'Produk'
  group by p.tanggal, p.id_penjualan
)
select tanggal, id_penjualan, 'Penerimaan penjualan'::text as keterangan,
       akun, nilai as debit, 0::numeric(14, 2) as kredit
from debit_penjualan
union all
select tanggal, id_penjualan, 'Pengakuan pendapatan'::text,
       akun, 0::numeric(14, 2), nilai
from pendapatan
union all
select tanggal, id_penjualan, 'Pengakuan HPP produk'::text,
       'Beban Pokok Penjualan'::text, nilai, 0::numeric(14, 2)
from hpp_produk
where nilai > 0
union all
select tanggal, id_penjualan, 'Pengurangan persediaan produk'::text,
       'Persediaan Produk'::text, 0::numeric(14, 2), nilai
from hpp_produk
where nilai > 0;

create or replace view view_jurnal_pelunasan with (security_invoker = true) as
select
  c.tanggal_bayar as tanggal,
  c.id_penjualan,
  coalesce(nullif(c.catatan, ''), 'Pembayaran cicilan ke-' || c.cicilan_ke)::text as keterangan,
  case c.metode_bayar when 'Transfer' then 'Bank' else 'Kas' end as akun,
  c.nominal as debit,
  0::numeric(14, 2) as kredit
from cicilan c
where c.status = 'Lunas'
union all
select
  c.tanggal_bayar,
  c.id_penjualan,
  coalesce(nullif(c.catatan, ''), 'Pelunasan piutang cicilan ke-' || c.cicilan_ke)::text,
  'Piutang Usaha'::text,
  0::numeric(14, 2),
  c.nominal
from cicilan c
where c.status = 'Lunas';

-- Membuat header, detail, total, dan mutasi stok dalam satu transaksi database.
create or replace function buat_penjualan(data_penjualan jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  transaksi_id bigint;
  baris jsonb;
  item_terpilih item%rowtype;
  kuantitas integer;
  jumlah_total numeric(14, 2) := 0;
  nilai_baris numeric(14, 2);
  daftar_item jsonb;
  tenor_cicilan integer;
  cicilan_ke integer;
  nominal_cicilan numeric(14, 2);
  tanggal_jatuh_tempo date;
  tanggal_transaksi date;
begin
  if coalesce(jsonb_typeof(data_penjualan->'items'), 'null') <> 'array' then
    raise exception 'Daftar item transaksi tidak valid.';
  end if;
  if jsonb_array_length(data_penjualan->'items') = 0 then
    raise exception 'Tambahkan minimal satu item pada transaksi.';
  end if;

  insert into penjualan (id_pelanggan, tanggal, metode_pembayaran, status_pembayaran)
  values (
    (data_penjualan->>'id_pelanggan')::bigint,
        coalesce(nullif(data_penjualan->>'tanggal', '')::date, current_date),
    data_penjualan->>'metode_pembayaran',
        case when data_penjualan->>'metode_pembayaran' = 'Kredit' then 'Belum Lunas'
          else coalesce(data_penjualan->>'status_pembayaran', 'Lunas') end
  )
  returning id_penjualan into transaksi_id;

  for baris in select value from jsonb_array_elements(data_penjualan->'items')
  loop
    kuantitas := (baris->>'jumlah')::integer;
    if kuantitas <= 0 then
      raise exception 'Jumlah item harus lebih dari nol.';
    end if;

    select * into item_terpilih
    from item
    where id_item = (baris->>'id_item')::bigint
    for update;

    if not found then
      raise exception 'Item tidak ditemukan.';
    end if;

    if item_terpilih.jenis = 'Produk' then
      update item
      set stok = stok - kuantitas
      where id_item = item_terpilih.id_item and stok >= kuantitas;
      if not found then
        raise exception 'Stok % tidak mencukupi.', item_terpilih.nama_item;
      end if;
    end if;

    nilai_baris := item_terpilih.harga_jual * kuantitas;
    insert into detail_penjualan (id_penjualan, id_item, jumlah, harga_satuan, subtotal)
    values (transaksi_id, item_terpilih.id_item, kuantitas, item_terpilih.harga_jual, nilai_baris);
    jumlah_total := jumlah_total + nilai_baris;
  end loop;

  update penjualan set total = jumlah_total where id_penjualan = transaksi_id;
  if data_penjualan->>'metode_pembayaran' = 'Kredit' then
    tenor_cicilan := nullif(data_penjualan->>'cicilan_bulan', '')::integer;
    tanggal_jatuh_tempo := nullif(data_penjualan->>'tanggal_jatuh_tempo_pertama', '')::date;
    select tanggal into tanggal_transaksi from penjualan where id_penjualan = transaksi_id;
    if tenor_cicilan is null or tenor_cicilan not in (2, 3, 6, 12) then
      raise exception 'Tenor cicilan harus 2, 3, 6, atau 12 bulan.';
    end if;
    if tanggal_jatuh_tempo is null or tanggal_jatuh_tempo < tanggal_transaksi then
      raise exception 'Tanggal jatuh tempo pertama harus sama atau setelah tanggal transaksi.';
    end if;
    if jumlah_total <= 0 then
      raise exception 'Total transaksi kredit harus lebih besar dari nol.';
    end if;

    nominal_cicilan := trunc(jumlah_total / tenor_cicilan, 2);
    for cicilan_ke in 1..tenor_cicilan loop
      insert into cicilan (id_penjualan, cicilan_ke, jatuh_tempo, nominal)
      values (
        transaksi_id,
        cicilan_ke,
        (tanggal_jatuh_tempo + make_interval(months => cicilan_ke - 1))::date,
        case when cicilan_ke = tenor_cicilan
          then jumlah_total - nominal_cicilan * (tenor_cicilan - 1)
          else nominal_cicilan
        end
      );
    end loop;
  end if;
  select coalesce(jsonb_agg(jsonb_build_object(
    'id_item', d.id_item, 'nama_item', i.nama_item, 'jumlah', d.jumlah,
    'harga_satuan', d.harga_satuan, 'subtotal', d.subtotal
  )), '[]'::jsonb)
  into daftar_item
  from detail_penjualan d join item i on i.id_item = d.id_item
  where d.id_penjualan = transaksi_id;

  return jsonb_build_object(
    'id_penjualan', transaksi_id,
    'total', jumlah_total,
    'items', daftar_item
  );
end;
$$;

grant execute on function buat_penjualan(jsonb) to anon, authenticated;

create or replace function konfirmasi_pembayaran_cicilan(
  cicilan_id bigint,
  tanggal_bayar_input date,
  metode_bayar_input text,
  catatan_input text default ''
)
returns cicilan
language plpgsql
security definer
set search_path = public
as $$
declare
  cicilan_terpilih public.cicilan%rowtype;
  cicilan_berikutnya integer;
begin
  select * into cicilan_terpilih
  from public.cicilan
  where id_cicilan = cicilan_id
  for update;

  if not found then
    raise exception 'Cicilan tidak ditemukan.';
  end if;
  if cicilan_terpilih.status = 'Lunas' then
    raise exception 'Cicilan ini sudah lunas.';
  end if;
  if tanggal_bayar_input is null then
    raise exception 'Tanggal pembayaran wajib diisi.';
  end if;
  if metode_bayar_input not in ('Tunai', 'Transfer') then
    raise exception 'Metode pembayaran harus Tunai atau Transfer.';
  end if;

  select min(cicilan_ke) into cicilan_berikutnya
  from public.cicilan
  where id_penjualan = cicilan_terpilih.id_penjualan and status = 'Belum';
  if cicilan_terpilih.cicilan_ke <> cicilan_berikutnya then
    raise exception 'Pembayaran cicilan harus berurutan.';
  end if;

  update public.cicilan
  set tanggal_bayar = tanggal_bayar_input,
      metode_bayar = metode_bayar_input,
      catatan = coalesce(catatan_input, ''),
      status = 'Lunas'
  where id_cicilan = cicilan_id
  returning * into cicilan_terpilih;

  update public.penjualan p
  set status_pembayaran = case when not exists (
    select 1 from public.cicilan c
    where c.id_penjualan = p.id_penjualan and c.status = 'Belum'
  ) then 'Lunas' else 'Belum Lunas' end
  where p.id_penjualan = cicilan_terpilih.id_penjualan;

  return cicilan_terpilih;
end;
$$;

grant execute on function konfirmasi_pembayaran_cicilan(bigint, date, text, text) to anon, authenticated;

