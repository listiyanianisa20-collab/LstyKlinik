-- DEMO ONLY: anon can read/write clinic data; do not use these open policies in production.
do $$
declare
  table_name text;
  policy_row record;
begin
  foreach table_name in array array['pelanggan', 'item', 'penjualan', 'detail_penjualan', 'cicilan']
  loop
    execute format('alter table public.%I enable row level security', table_name);
    for policy_row in
      select * from (values
        ('select', 'using (true)'),
        ('insert', 'with check (true)'),
        ('update', 'using (true) with check (true)'),
        ('delete', 'using (true)')
      ) as demo_policies(operation, clause)
    loop
      execute format('drop policy if exists demo_anon_%1$s on public.%2$I', policy_row.operation, table_name);
      execute format(
        'create policy demo_anon_%1$s on public.%2$I for %3$s to anon %4$s',
        policy_row.operation,
        table_name,
        upper(policy_row.operation),
        policy_row.clause
      );
    end loop;
  end loop;
end;
$$;

