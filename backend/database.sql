-- Skema Sistem Informasi Akuntansi Penjualan Lsty Klinik

create table if not exists pelanggan (
  id_pelanggan bigint generated by default as identity primary key,
  nama text not null check (length(trim(nama)) > 0),
  no_hp text not null check (length(trim(no_hp)) > 0),
  alamat text not null default '',
  tanggal_daftar date not null default current_date
);

-- Pulihkan tabel lama yang sudah ada tanpa kolom kunci sesuai ERD.
do $$
begin
  if not exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'pelanggan' and column_name = 'id_pelanggan'
  ) then
    if exists (
      select 1 from information_schema.columns
      where table_schema = 'public' and table_name = 'pelanggan' and column_name = 'id'
    ) then
      alter table public.pelanggan rename column id to id_pelanggan;
    else
      alter table public.pelanggan
        add column id_pelanggan bigint generated by default as identity;
    end if;
  end if;

  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.pelanggan'::regclass and contype = 'p'
  ) then
    alter table public.pelanggan
      add constraint pelanggan_pkey primary key (id_pelanggan);
  elsif not exists (
    select 1 from pg_constraint
    where conrelid = 'public.pelanggan'::regclass
      and contype in ('p', 'u')
      and conkey = array[(
        select attnum from pg_attribute
        where attrelid = 'public.pelanggan'::regclass and attname = 'id_pelanggan'
      )]::smallint[]
  ) then
    alter table public.pelanggan
      add constraint pelanggan_id_pelanggan_key unique (id_pelanggan);
  end if;
end;
$$;

alter table public.pelanggan add column if not exists nama text;
alter table public.pelanggan add column if not exists no_hp text;
alter table public.pelanggan add column if not exists alamat text;
alter table public.pelanggan add column if not exists tanggal_daftar date;

update public.pelanggan
set nama = coalesce(nullif(trim(nama), ''), 'Pelanggan ' || id_pelanggan::text),
    no_hp = coalesce(nullif(trim(no_hp), ''), 'Belum diisi'),
    alamat = coalesce(alamat, ''),
    tanggal_daftar = coalesce(tanggal_daftar, current_date);

alter table public.pelanggan alter column nama set not null;
alter table public.pelanggan alter column no_hp set default 'Belum diisi';
alter table public.pelanggan alter column no_hp set not null;
alter table public.pelanggan alter column alamat set default '';
alter table public.pelanggan alter column alamat set not null;
alter table public.pelanggan alter column tanggal_daftar set default current_date;
alter table public.pelanggan alter column tanggal_daftar set not null;

-- Pertahankan nomor telepon lama, tetapi jangan wajibkan kolom non-ERD saat insert baru.
do $$
declare
  kolom_lama record;
begin
  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'pelanggan' and column_name = 'telepon'
  ) then
    execute $sql$
      update public.pelanggan
      set no_hp = nullif(trim(telepon::text), '')
      where no_hp = 'Belum diisi' and nullif(trim(telepon::text), '') is not null
    $sql$;
  end if;

  for kolom_lama in
    select column_name
    from information_schema.columns
    where table_schema = 'public'
      and table_name = 'pelanggan'
      and is_nullable = 'NO'
      and is_identity = 'NO'
      and column_default is null
      and column_name not in ('id_pelanggan', 'nama', 'no_hp', 'alamat', 'tanggal_daftar')
  loop
    execute format('alter table public.pelanggan alter column %I drop not null', kolom_lama.column_name);
  end loop;
end;
$$;

create table if not exists item (
  id_item bigint generated by default as identity primary key,
  nama_item text not null check (length(trim(nama_item)) > 0),
  jenis text not null check (jenis in ('Produk', 'Jasa Treatment')),
  harga_jual numeric(14, 2) not null check (harga_jual >= 0),
  harga_pokok numeric(14, 2) not null default 0 check (harga_pokok >= 0),
  stok integer,
  constraint item_stok_jenis_check check (
    (jenis = 'Produk' and stok is not null and stok >= 0)
    or (jenis = 'Jasa Treatment' and stok is null and harga_pokok = 0)
  )
);

create table if not exists penjualan (
  id_penjualan bigint generated by default as identity primary key,
  id_pelanggan bigint not null references pelanggan(id_pelanggan),
  tanggal date not null default current_date,
  metode_pembayaran text not null check (metode_pembayaran in ('Tunai', 'Transfer', 'Kredit')),
  status_pembayaran text not null default 'Lunas' check (status_pembayaran in ('Lunas', 'Belum Lunas')),
  total numeric(14, 2) not null default 0 check (total >= 0),
  tenor integer,
  jadwal_cicilan jsonb not null default '[]'::jsonb
);

alter table public.penjualan add column if not exists tenor integer;
alter table public.penjualan add column if not exists jadwal_cicilan jsonb not null default '[]'::jsonb;

create table if not exists detail_penjualan (
  id_detail bigint generated by default as identity primary key,
  id_penjualan bigint not null references penjualan(id_penjualan) on delete cascade,
  id_item bigint not null references item(id_item),
  jumlah integer not null check (jumlah > 0),
  harga_satuan numeric(14, 2) not null check (harga_satuan >= 0),
  subtotal numeric(14, 2) not null check (subtotal >= 0)
);

drop view if exists public.view_buku_besar;
