-- Migrasikan jadwal dan pembayaran lama sebelum menghapus tabel cicilan.
do $$
declare
  object_row record;
begin
  if to_regclass('public.cicilan') is not null then
    execute $migration$
      update public.penjualan p
      set jadwal_cicilan = (
        select coalesce(jsonb_agg(jsonb_build_object(
          'cicilan_ke', c.cicilan_ke,
          'jatuh_tempo', c.jatuh_tempo,
          'nominal', c.nominal,
          'tanggal_bayar', c.tanggal_bayar,
          'metode_bayar', c.metode_bayar,
          'status', case when c.status = 'Lunas' then 'Lunas' else 'Belum Lunas' end,
          'catatan', coalesce(c.catatan, '')
        ) order by c.cicilan_ke), '[]'::jsonb)
        from public.cicilan c
        where c.id_penjualan = p.id_penjualan
      ),
      tenor = (
        select count(*)::integer
        from public.cicilan c
        where c.id_penjualan = p.id_penjualan
      )
      where exists (
        select 1 from public.cicilan c where c.id_penjualan = p.id_penjualan
      )
    $migration$;

    for object_row in
      select policyname
      from pg_policies
      where schemaname = 'public' and tablename = 'cicilan'
    loop
      execute format('drop policy %I on public.cicilan', object_row.policyname);
    end loop;

    for object_row in
      select tgname
      from pg_trigger
      where tgrelid = 'public.cicilan'::regclass and not tgisinternal
    loop
      execute format('drop trigger %I on public.cicilan', object_row.tgname);
    end loop;

    drop table public.cicilan;
  end if;
end;
$$;

