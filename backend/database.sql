-- Satu baris laporan mewakili satu item pada detail transaksi.
create view view_laporan_penjualan with (security_invoker = true) as
select
  (c.value->>'tanggal_bayar')::date,
  p.id_penjualan,
  pl.nama as nama_pelanggan,
  i.id_item,
  i.nama_item,
  i.jenis,
  d.jumlah,
  d.harga_satuan,
  d.subtotal,
  p.metode_pembayaran,
  p.status_pembayaran
from penjualan p
join pelanggan pl on pl.id_pelanggan = p.id_pelanggan
join detail_penjualan d on d.id_penjualan = p.id_penjualan
join item i on i.id_item = d.id_item;

-- Jurnal berpasangan: kas/piutang, pendapatan, serta HPP dan persediaan produk.
create view view_jurnal_umum with (security_invoker = true) as
with debit_penjualan as (
  select
    p.tanggal,
    p.id_penjualan,
    case p.metode_pembayaran
      when 'Kredit' then 'Piutang Usaha'
      when 'Transfer' then 'Bank'
      else 'Kas'
    end as akun,
    p.total as nilai
  from penjualan p
), pendapatan as (
  select
    p.tanggal,
    p.id_penjualan,
    case i.jenis
      when 'Produk' then 'Pendapatan Penjualan Produk'
      else 'Pendapatan Jasa Treatment'
    end as akun,
    sum(d.subtotal) as nilai
  from penjualan p
  join detail_penjualan d on d.id_penjualan = p.id_penjualan
  join item i on i.id_item = d.id_item
  group by p.tanggal, p.id_penjualan, i.jenis
), hpp_produk as (
  select
    p.tanggal,
    p.id_penjualan,
    sum(d.jumlah * i.harga_pokok) as nilai
  from penjualan p
  join detail_penjualan d on d.id_penjualan = p.id_penjualan
  join item i on i.id_item = d.id_item
  where i.jenis = 'Produk'
  group by p.tanggal, p.id_penjualan
)
select tanggal, id_penjualan, 'Penerimaan penjualan'::text as keterangan,
       akun, nilai as debit, 0::numeric(14, 2) as kredit
from debit_penjualan
union all
select tanggal, id_penjualan, 'Pengakuan pendapatan'::text,
       akun, 0::numeric(14, 2), nilai
from pendapatan
union all
select tanggal, id_penjualan, 'Pengakuan HPP produk'::text,
       'Beban Pokok Penjualan'::text, nilai, 0::numeric(14, 2)
from hpp_produk
where nilai > 0
union all
select tanggal, id_penjualan, 'Pengurangan persediaan produk'::text,
       'Persediaan Produk'::text, 0::numeric(14, 2), nilai
from hpp_produk
where nilai > 0;

create view view_jurnal_pelunasan with (security_invoker = true) as
select
  (c.value->>'tanggal_bayar')::date as tanggal,
  p.id_penjualan,
  coalesce(nullif(c.value->>'catatan', ''), 'Pembayaran cicilan ke-' || (c.value->>'cicilan_ke'))::text as keterangan,
  case c.value->>'metode_bayar' when 'Transfer' then 'Bank' else 'Kas' end as akun,
  (c.value->>'nominal')::numeric(14, 2) as debit,
  0::numeric(14, 2) as kredit
from penjualan p
cross join lateral jsonb_array_elements(p.jadwal_cicilan) as c(value)
where c.value->>'status' = 'Lunas'
union all
select
  p.tanggal,
  p.id_penjualan,
  coalesce(nullif(c.value->>'catatan', ''), 'Pelunasan piutang cicilan ke-' || (c.value->>'cicilan_ke'))::text,
  'Piutang Usaha'::text,
  0::numeric(14, 2),
  (c.value->>'nominal')::numeric(14, 2)
from penjualan p
cross join lateral jsonb_array_elements(p.jadwal_cicilan) as c(value)
where c.value->>'status' = 'Lunas';

create view view_laporan_pelunasan with (security_invoker = true) as
select
  (c.value->>'tanggal_bayar')::date as tanggal,
  p.id_penjualan,
  p.id_pelanggan,
  pl.nama as nama_pelanggan,
  (c.value->>'cicilan_ke')::integer as cicilan_ke,
  c.value->>'metode_bayar' as metode_pembayaran,
  coalesce(nullif(c.value->>'catatan', ''), 'Pembayaran cicilan') as keterangan,
  (c.value->>'nominal')::numeric(14, 2) as nominal
from penjualan p
join pelanggan pl on pl.id_pelanggan = p.id_pelanggan
cross join lateral jsonb_array_elements(p.jadwal_cicilan) as c(value)
where c.value->>'status' = 'Lunas';

create view view_piutang with (security_invoker = true) as
select
  p.id_penjualan,
  p.id_pelanggan,
  p.tanggal,
  p.metode_pembayaran,
  p.status_pembayaran,
  p.total,
  p.tenor,
  coalesce(sum(case when c.value->>'status' = 'Lunas' then (c.value->>'nominal')::numeric else 0 end), 0)::numeric(14, 2) as total_dibayar,
  coalesce(sum(case when c.value->>'status' <> 'Lunas' then (c.value->>'nominal')::numeric else 0 end), 0)::numeric(14, 2) as sisa_pembayaran,
  count(c.value)::integer as jumlah_cicilan,
  count(*) filter (where c.value->>'status' <> 'Lunas')::integer as sisa_tenor,
  min((c.value->>'jatuh_tempo')::date) filter (where c.value->>'status' <> 'Lunas') as jatuh_tempo_berikutnya
from penjualan p
left join lateral jsonb_array_elements(p.jadwal_cicilan) as c(value) on true
where p.metode_pembayaran = 'Kredit'
group by p.id_penjualan;

create view view_laba_rugi with (security_invoker = true) as
with per_penjualan as (
  select
    p.tanggal,
    p.id_penjualan,
    sum(d.subtotal)::numeric(14, 2) as pendapatan,
    sum(case when i.jenis = 'Produk' then d.jumlah * i.harga_pokok else 0 end)::numeric(14, 2) as hpp
  from penjualan p
  join detail_penjualan d on d.id_penjualan = p.id_penjualan
  join item i on i.id_item = d.id_item
  group by p.tanggal, p.id_penjualan
)
select tanggal, id_penjualan, 1 as urutan, 'Pendapatan'::text as akun, pendapatan as nilai from per_penjualan
union all
select tanggal, id_penjualan, 2, 'Harga Pokok Penjualan'::text, -hpp from per_penjualan
union all
select tanggal, id_penjualan, 3, 'Beban Operasional'::text, 0::numeric(14, 2) from per_penjualan
union all
select tanggal, id_penjualan, 4, 'Laba Bersih'::text, pendapatan - hpp from per_penjualan;

create view view_buku_besar with (security_invoker = true) as
select tanggal, id_penjualan, keterangan, akun, debit, kredit from view_jurnal_umum
union all
select tanggal, id_penjualan, keterangan, akun, debit, kredit from view_jurnal_pelunasan;

-- Membuat header, detail, total, dan mutasi stok dalam satu transaksi database.
create or replace function buat_penjualan(data_penjualan jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  transaksi_id bigint;
  baris jsonb;
  item_terpilih item%rowtype;
  kuantitas integer;
  jumlah_total numeric(14, 2) := 0;
  nilai_baris numeric(14, 2);
  daftar_item jsonb;
  tenor_cicilan integer;
  cicilan_ke integer;
  nominal_cicilan numeric(14, 2);
  tanggal_jatuh_tempo date;
  tanggal_transaksi date;
  jadwal jsonb := '[]'::jsonb;
begin
  if coalesce(jsonb_typeof(data_penjualan->'items'), 'null') <> 'array' then
    raise exception 'Daftar item transaksi tidak valid.';
  end if;
  if jsonb_array_length(data_penjualan->'items') = 0 then
    raise exception 'Tambahkan minimal satu item pada transaksi.';
  end if;

  insert into penjualan (id_pelanggan, tanggal, metode_pembayaran, status_pembayaran)
  values (
    (data_penjualan->>'id_pelanggan')::bigint,
        coalesce(nullif(data_penjualan->>'tanggal', '')::date, current_date),
    data_penjualan->>'metode_pembayaran',
        case when data_penjualan->>'metode_pembayaran' = 'Kredit' then 'Belum Lunas'
          else coalesce(data_penjualan->>'status_pembayaran', 'Lunas') end
  )
  returning id_penjualan into transaksi_id;

  for baris in select value from jsonb_array_elements(data_penjualan->'items')
  loop
    kuantitas := (baris->>'jumlah')::integer;
    if kuantitas <= 0 then
      raise exception 'Jumlah item harus lebih dari nol.';
    end if;

    select * into item_terpilih
    from item
    where id_item = (baris->>'id_item')::bigint
    for update;

    if not found then
      raise exception 'Item tidak ditemukan.';
    end if;

    if item_terpilih.jenis = 'Produk' then
      update item
      set stok = stok - kuantitas
      where id_item = item_terpilih.id_item and stok >= kuantitas;
      if not found then
        raise exception 'Stok % tidak mencukupi.', item_terpilih.nama_item;
      end if;
    end if;

    nilai_baris := item_terpilih.harga_jual * kuantitas;
    insert into detail_penjualan (id_penjualan, id_item, jumlah, harga_satuan, subtotal)
    values (transaksi_id, item_terpilih.id_item, kuantitas, item_terpilih.harga_jual, nilai_baris);
    jumlah_total := jumlah_total + nilai_baris;
  end loop;

  update penjualan set total = jumlah_total where id_penjualan = transaksi_id;
  if data_penjualan->>'metode_pembayaran' = 'Kredit' then
    tenor_cicilan := nullif(data_penjualan->>'cicilan_bulan', '')::integer;
    tanggal_jatuh_tempo := nullif(data_penjualan->>'tanggal_jatuh_tempo_pertama', '')::date;
    select tanggal into tanggal_transaksi from penjualan where id_penjualan = transaksi_id;
    if tenor_cicilan is null or tenor_cicilan not in (2, 3, 6, 12) then
      raise exception 'Tenor cicilan harus 2, 3, 6, atau 12 bulan.';
    end if;
    if tanggal_jatuh_tempo is null or tanggal_jatuh_tempo < tanggal_transaksi then
      raise exception 'Tanggal jatuh tempo pertama harus sama atau setelah tanggal transaksi.';
    end if;
    if jumlah_total <= 0 then
      raise exception 'Total transaksi kredit harus lebih besar dari nol.';
    end if;

    nominal_cicilan := trunc(jumlah_total / tenor_cicilan, 2);
    for cicilan_ke in 1..tenor_cicilan loop
      jadwal := jadwal || jsonb_build_array(jsonb_build_object(
        'cicilan_ke', cicilan_ke,
        'jatuh_tempo', (tanggal_jatuh_tempo + make_interval(months => cicilan_ke - 1))::date,
        'nominal', case when cicilan_ke = tenor_cicilan
          then jumlah_total - nominal_cicilan * (tenor_cicilan - 1)
          else nominal_cicilan
        end,
        'tanggal_bayar', null,
        'metode_bayar', null,
        'status', 'Belum Lunas',
        'catatan', ''
      ));
    end loop;
    update penjualan
    set tenor = tenor_cicilan, jadwal_cicilan = jadwal
    where id_penjualan = transaksi_id;
  end if;
  select coalesce(jsonb_agg(jsonb_build_object(
    'id_item', d.id_item, 'nama_item', i.nama_item, 'jumlah', d.jumlah,
    'harga_satuan', d.harga_satuan, 'subtotal', d.subtotal
  )), '[]'::jsonb)
  into daftar_item
  from detail_penjualan d join item i on i.id_item = d.id_item
  where d.id_penjualan = transaksi_id;

  return jsonb_build_object(
    'id_penjualan', transaksi_id,
    'total', jumlah_total,
    'items', daftar_item
  );
end;
$$;

grant execute on function buat_penjualan(jsonb) to anon, authenticated;

create or replace function konfirmasi_pembayaran_cicilan(
  id_penjualan_input bigint,
  cicilan_ke_input integer,
  tanggal_bayar_input date,
  metode_bayar_input text,
  catatan_input text default ''
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  penjualan_terpilih public.penjualan%rowtype;
  cicilan_terpilih jsonb;
  jadwal_baru jsonb;
  cicilan_berikutnya integer;
begin
  select * into penjualan_terpilih
  from public.penjualan
  where id_penjualan = id_penjualan_input
  for update;

  if not found then
    raise exception 'Transaksi piutang tidak ditemukan.';
  end if;
  select value into cicilan_terpilih
  from jsonb_array_elements(penjualan_terpilih.jadwal_cicilan) as schedule(value)
  where (value->>'cicilan_ke')::integer = cicilan_ke_input;

  if not found then
    raise exception 'Cicilan tidak ditemukan.';
  end if;
  if cicilan_terpilih->>'status' = 'Lunas' then
    raise exception 'Cicilan ini sudah lunas.';
  end if;
  if tanggal_bayar_input is null then
    raise exception 'Tanggal pembayaran wajib diisi.';
  end if;
  if metode_bayar_input not in ('Tunai', 'Transfer') then
    raise exception 'Metode pembayaran harus Tunai atau Transfer.';
  end if;

  select min((value->>'cicilan_ke')::integer) into cicilan_berikutnya
  from jsonb_array_elements(penjualan_terpilih.jadwal_cicilan) as schedule(value)
  where value->>'status' <> 'Lunas';
  if cicilan_ke_input <> cicilan_berikutnya then
    raise exception 'Pembayaran cicilan harus berurutan.';
  end if;

  select coalesce(jsonb_agg(
    case when (value->>'cicilan_ke')::integer = cicilan_ke_input then
      value || jsonb_build_object(
        'tanggal_bayar', tanggal_bayar_input,
        'metode_bayar', metode_bayar_input,
        'catatan', coalesce(catatan_input, ''),
        'status', 'Lunas'
      )
    else value end
    order by ordinal
  ), '[]'::jsonb)
  into jadwal_baru
  from jsonb_array_elements(penjualan_terpilih.jadwal_cicilan) with ordinality as schedule(value, ordinal);

  update public.penjualan p
  set jadwal_cicilan = jadwal_baru,
      status_pembayaran = case when not exists (
        select 1 from jsonb_array_elements(jadwal_baru) as schedule(value)
        where value->>'status' <> 'Lunas'
      ) then 'Lunas' else 'Belum Lunas' end
  where p.id_penjualan = id_penjualan_input;

  return cicilan_terpilih || jsonb_build_object(
    'tanggal_bayar', tanggal_bayar_input,
    'metode_bayar', metode_bayar_input,
    'catatan', coalesce(catatan_input, ''),
    'status', 'Lunas'
  );
end;
$$;

